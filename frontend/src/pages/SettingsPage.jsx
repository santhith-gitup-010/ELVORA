/**
 * Settings Page
 * System configuration, PDF report generation, and account info
 */

import { useState, useEffect } from 'react';
import { useAuth } from '../context/AuthContext';
import { useTheme } from '../context/ThemeContext';
import { dashboardAPI, booksAPI, studentsAPI, transactionsAPI } from '../services/api';
import LoadingSpinner from '../components/common/LoadingSpinner';
import toast from 'react-hot-toast';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import {
    HiOutlineCog6Tooth, HiOutlineDocumentArrowDown, HiOutlineSun,
    HiOutlineMoon, HiOutlineShieldCheck, HiOutlineServerStack,
    HiOutlineChartBarSquare, HiOutlineBookOpen, HiOutlineAcademicCap,
    HiOutlineArrowsRightLeft, HiOutlineBanknotes
} from 'react-icons/hi2';

const SettingsPage = () => {
    const { user } = useAuth();
    const { isDark, toggleTheme } = useTheme();
    const [stats, setStats] = useState(null);
    const [loading, setLoading] = useState(true);
    const [generating, setGenerating] = useState(false);

    useEffect(() => {
        fetchStats();
    }, []);

    const fetchStats = async () => {
        try {
            const res = await dashboardAPI.getStats();
            setStats(res.data.data);
        } catch { } finally { setLoading(false); }
    };

    const generatePDFReport = async (type) => {
        setGenerating(true);
        try {
            const doc = new jsPDF();
            const pageWidth = doc.internal.pageSize.getWidth();

            doc.setFillColor(99, 102, 241);
            doc.rect(0, 0, pageWidth, 40, 'F');
            doc.setFont('helvetica', 'bold');
            doc.setTextColor(255, 255, 255);
            doc.setFontSize(22);
            doc.text('ELVORA', 14, 20);
            doc.setFontSize(10);
            doc.setFont('helvetica', 'normal');
            doc.text('Smart Library Management System', 14, 28);
            doc.text(`Generated: ${new Date().toLocaleString()}`, pageWidth - 14, 20, { align: 'right' });
            doc.text(`Generated by: ${user?.name || 'Admin'}`, pageWidth - 14, 28, { align: 'right' });

            doc.setTextColor(15, 23, 42);
            doc.setFontSize(16);
            doc.setFont('helvetica', 'bold');

            if (type === 'books') {
                doc.text('Books Inventory Report', 14, 52);
                const res = await booksAPI.getAll({ limit: 200 });
                const books = res.data.data.books;
                autoTable(doc, { startY: 60, head: [['#', 'Title', 'Author', 'Category', 'Barcode', 'Available', 'Total', 'Location']], body: books.map((b, i) => [i + 1, b.title, b.author, b.category, b.barcode, b.availableCount, b.totalCount, b.location]), headStyles: { fillColor: [99, 102, 241], fontSize: 8 }, bodyStyles: { fontSize: 7 }, alternateRowStyles: { fillColor: [248, 250, 252] }, margin: { top: 60 }, styles: { cellPadding: 3 } });
                const finalY = doc.lastAutoTable.finalY + 15;
                doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('Summary', 14, finalY);
                doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
                doc.text(`Total Books: ${books.length}`, 14, finalY + 8);
                doc.text(`Total Copies: ${books.reduce((s, b) => s + b.totalCount, 0)}`, 14, finalY + 14);
                doc.text(`Available Copies: ${books.reduce((s, b) => s + b.availableCount, 0)}`, 14, finalY + 20);
            } else if (type === 'students') {
                doc.text('Student Registry Report', 14, 52);
                const res = await studentsAPI.getAll({ limit: 200 });
                const students = res.data.data.students;
                autoTable(doc, { startY: 60, head: [['#', 'Student ID', 'Name', 'Department', 'Year', 'Email', 'Phone', 'Books Issued']], body: students.map((s, i) => [i + 1, s.studentId, s.name, s.department, s.year, s.email, s.phone, `${s.booksIssued}/5`]), headStyles: { fillColor: [6, 182, 212], fontSize: 8 }, bodyStyles: { fontSize: 7 }, alternateRowStyles: { fillColor: [248, 250, 252] }, styles: { cellPadding: 3 } });
                const finalY = doc.lastAutoTable.finalY + 15;
                doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('Summary', 14, finalY);
                doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
                doc.text(`Total Students: ${students.length}`, 14, finalY + 8);
                const depts = [...new Set(students.map(s => s.department))];
                doc.text(`Departments: ${depts.join(', ')}`, 14, finalY + 14);
            } else if (type === 'transactions') {
                doc.text('Transactions Report', 14, 52);
                const res = await transactionsAPI.getAll({ limit: 200 });
                const txns = res.data.data.transactions;
                autoTable(doc, { startY: 60, head: [['#', 'Transaction ID', 'Student', 'Book', 'Issue Date', 'Due Date', 'Status', 'Fine (₹)']], body: txns.map((t, i) => [i + 1, t.transactionId, t.student?.name || 'N/A', t.book?.title || 'N/A', new Date(t.issueDate).toLocaleDateString(), new Date(t.dueDate).toLocaleDateString(), t.status.toUpperCase(), t.fineAmount > 0 ? `₹${t.fineAmount}` : '—']), headStyles: { fillColor: [59, 130, 246], fontSize: 8 }, bodyStyles: { fontSize: 7 }, alternateRowStyles: { fillColor: [248, 250, 252] }, styles: { cellPadding: 3 } });
                const finalY = doc.lastAutoTable.finalY + 15;
                doc.setFontSize(11); doc.setFont('helvetica', 'bold'); doc.text('Summary', 14, finalY);
                doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
                const issued = txns.filter(t => t.status === 'issued').length;
                const returned = txns.filter(t => t.status === 'returned').length;
                const overdue = txns.filter(t => t.status === 'overdue').length;
                const totalFines = txns.reduce((s, t) => s + t.fineAmount, 0);
                doc.text(`Total: ${txns.length} | Issued: ${issued} | Returned: ${returned} | Overdue: ${overdue}`, 14, finalY + 8);
                doc.text(`Total Fines Collected: ₹${totalFines}`, 14, finalY + 14);
            } else if (type === 'overview') {
                doc.text('Library Overview Report', 14, 52);
                const [, , tRes] = await Promise.all([booksAPI.getAll({ limit: 5 }), studentsAPI.getAll({ limit: 5 }), transactionsAPI.getAll({ limit: 10 })]);
                doc.setFontSize(12); doc.setFont('helvetica', 'bold'); doc.text('Key Metrics', 14, 62);
                const overviewData = [['Total Books', String(stats?.totalBooks || 0)], ['Total Students', String(stats?.totalStudents || 0)], ['Books Currently Issued', String(stats?.issuedBooks || 0)], ['Overdue Books', String(stats?.overdueBooks || 0)], ['Books Returned', String(stats?.returnedBooks || 0)], ['Total Fines (₹)', `₹${stats?.totalFines || 0}`]];
                autoTable(doc, { startY: 68, body: overviewData, theme: 'grid', columnStyles: { 0: { fontStyle: 'bold', cellWidth: 80 }, 1: { halign: 'right', cellWidth: 60 } }, bodyStyles: { fontSize: 10 }, styles: { cellPadding: 6 } });
                let y = doc.lastAutoTable.finalY + 15;
                doc.setFontSize(12); doc.setFont('helvetica', 'bold'); doc.text('Recent Transactions', 14, y);
                autoTable(doc, { startY: y + 6, head: [['ID', 'Student', 'Book', 'Status', 'Date']], body: tRes.data.data.transactions.map(t => [t.transactionId, t.student?.name || 'N/A', t.book?.title || 'N/A', t.status.toUpperCase(), new Date(t.createdAt).toLocaleDateString()]), headStyles: { fillColor: [99, 102, 241], fontSize: 8 }, bodyStyles: { fontSize: 7 }, styles: { cellPadding: 3 } });
            }

            const pageCount = doc.internal.getNumberOfPages();
            for (let i = 1; i <= pageCount; i++) {
                doc.setPage(i);
                const pgHeight = doc.internal.pageSize.getHeight();
                doc.setFontSize(8); doc.setTextColor(148, 163, 184);
                doc.text(`ELVORA Smart Library Management System | Page ${i} of ${pageCount}`, pageWidth / 2, pgHeight - 10, { align: 'center' });
            }
            doc.save(`ELVORA_${type}_report_${new Date().toISOString().slice(0, 10)}.pdf`);
            toast.success(`${type.charAt(0).toUpperCase() + type.slice(1)} report downloaded!`);
        } catch (err) {
            toast.error('Failed to generate report');
            console.error(err);
        } finally { setGenerating(false); }
    };

    const exportCSV = async (type) => {
        try {
            let csvContent = '';
            if (type === 'books') {
                const res = await booksAPI.getAll({ limit: 200 }); const books = res.data.data.books;
                csvContent = 'Title,Author,Category,Barcode,Available,Total,Location\n';
                csvContent += books.map(b => `"${b.title}","${b.author}","${b.category}","${b.barcode}",${b.availableCount},${b.totalCount},"${b.location}"`).join('\n');
            } else if (type === 'students') {
                const res = await studentsAPI.getAll({ limit: 200 }); const students = res.data.data.students;
                csvContent = 'StudentID,Name,Department,Year,Email,Phone,BooksIssued\n';
                csvContent += students.map(s => `"${s.studentId}","${s.name}","${s.department}",${s.year},"${s.email}","${s.phone}",${s.booksIssued}`).join('\n');
            } else if (type === 'transactions') {
                const res = await transactionsAPI.getAll({ limit: 200 }); const txns = res.data.data.transactions;
                csvContent = 'TransactionID,Student,Book,IssueDate,DueDate,Status,Fine\n';
                csvContent += txns.map(t => `"${t.transactionId}","${t.student?.name || ''}","${t.book?.title || ''}","${new Date(t.issueDate).toLocaleDateString()}","${new Date(t.dueDate).toLocaleDateString()}","${t.status}",${t.fineAmount}`).join('\n');
            }
            const blob = new Blob([csvContent], { type: 'text/csv' });
            const url = URL.createObjectURL(blob);
            const a = document.createElement('a'); a.href = url; a.download = `ELVORA_${type}_${new Date().toISOString().slice(0, 10)}.csv`; a.click();
            URL.revokeObjectURL(url);
            toast.success(`${type} CSV exported!`);
        } catch { toast.error('Export failed'); }
    };

    if (loading) return <LoadingSpinner text="Loading settings..." />;

    const reportCards = [
        { type: 'overview', label: 'Library Overview', desc: 'Complete summary with stats and recent activity', icon: HiOutlineChartBarSquare, color: '#6366f1' },
        { type: 'books', label: 'Books Inventory', desc: 'Full catalog with availability and locations', icon: HiOutlineBookOpen, color: '#10b981' },
        { type: 'students', label: 'Student Registry', desc: 'All registered students with departments', icon: HiOutlineAcademicCap, color: '#06b6d4' },
        { type: 'transactions', label: 'Transactions Log', desc: 'Issue/return records with fines breakdown', icon: HiOutlineArrowsRightLeft, color: '#f59e0b' },
    ];

    return (
        <div className="page-sections animate-fade-in">
            <div>
                <h1 style={{ fontSize: '1.5rem', fontWeight: 700, color: 'var(--text-primary)', display: 'flex', alignItems: 'center', gap: 8 }}>
                    <HiOutlineCog6Tooth style={{ width: 28, height: 28, color: '#6366f1' }} /> Settings
                </h1>
                <p style={{ fontSize: '0.875rem', marginTop: 4, color: 'var(--text-secondary)' }}>
                    System configuration and report generation
                </p>
            </div>

            {/* Quick Stats */}
            <div className="settings-stats-grid">
                {[
                    { label: 'Books', val: stats?.totalBooks || 0, icon: HiOutlineBookOpen, color: '#6366f1' },
                    { label: 'Students', val: stats?.totalStudents || 0, icon: HiOutlineAcademicCap, color: '#06b6d4' },
                    { label: 'Issued', val: stats?.issuedBooks || 0, icon: HiOutlineArrowsRightLeft, color: '#3b82f6' },
                    { label: 'Fines (₹)', val: stats?.totalFines || 0, icon: HiOutlineBanknotes, color: '#f59e0b' },
                ].map(s => (
                    <div key={s.label} className="glass-card" style={{ padding: 16, display: 'flex', alignItems: 'center', gap: 12 }}>
                        <div style={{ width: 40, height: 40, borderRadius: 12, display: 'flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0, background: `${s.color}15` }}>
                            <s.icon style={{ width: 20, height: 20, color: s.color }} />
                        </div>
                        <div>
                            <p style={{ fontSize: '1.25rem', fontWeight: 700, color: 'var(--text-primary)' }}>{s.val.toLocaleString()}</p>
                            <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>{s.label}</p>
                        </div>
                    </div>
                ))}
            </div>

            <div className="settings-grid">
                {/* PDF Reports */}
                <div className="glass-card" style={{ padding: 24 }}>
                    <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 16 }}>
                        <HiOutlineDocumentArrowDown style={{ width: 20, height: 20, color: '#6366f1' }} />
                        <h2 style={{ fontWeight: 700, fontSize: '1rem', color: 'var(--text-primary)' }}>Generate PDF Reports</h2>
                    </div>
                    <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                        {reportCards.map(card => (
                            <div key={card.type} className="report-card">
                                <div style={{ width: 40, height: 40, borderRadius: 12, display: 'flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0, background: `${card.color}15` }}>
                                    <card.icon style={{ width: 20, height: 20, color: card.color }} />
                                </div>
                                <div className="report-info">
                                    <p style={{ fontSize: '0.875rem', fontWeight: 500, color: 'var(--text-primary)' }}>{card.label}</p>
                                    <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>{card.desc}</p>
                                </div>
                                <div className="report-actions">
                                    <button onClick={() => generatePDFReport(card.type)} disabled={generating} className="btn btn-primary btn-sm">PDF</button>
                                    {card.type !== 'overview' && (
                                        <button onClick={() => exportCSV(card.type)} className="btn btn-secondary btn-sm">CSV</button>
                                    )}
                                </div>
                            </div>
                        ))}
                    </div>
                </div>

                {/* System Settings */}
                <div style={{ display: 'flex', flexDirection: 'column', gap: 24 }}>
                    {/* Appearance */}
                    <div className="glass-card" style={{ padding: 24 }}>
                        <h2 style={{ fontWeight: 700, fontSize: '1rem', marginBottom: 16, color: 'var(--text-primary)' }}>Appearance</h2>
                        <div className="info-row">
                            <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                                {isDark ? <HiOutlineMoon style={{ width: 20, height: 20, color: '#818cf8' }} /> : <HiOutlineSun style={{ width: 20, height: 20, color: '#f59e0b' }} />}
                                <div>
                                    <p style={{ fontSize: '0.875rem', fontWeight: 500, color: 'var(--text-primary)' }}>{isDark ? 'Dark Mode' : 'Light Mode'}</p>
                                    <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>Toggle interface theme</p>
                                </div>
                            </div>
                            <button onClick={toggleTheme} className={`toggle-switch ${isDark ? 'on' : 'off'}`}>
                                <span className="toggle-knob" />
                            </button>
                        </div>
                    </div>

                    {/* Account Info */}
                    <div className="glass-card" style={{ padding: 24 }}>
                        <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 16 }}>
                            <HiOutlineShieldCheck style={{ width: 20, height: 20, color: '#10b981' }} />
                            <h2 style={{ fontWeight: 700, fontSize: '1rem', color: 'var(--text-primary)' }}>Account</h2>
                        </div>
                        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                            {[
                                { label: 'Name', value: user?.name || 'Admin' },
                                { label: 'Email', value: user?.email || 'admin@elvora.com' },
                                { label: 'Role', value: (user?.role || 'admin').charAt(0).toUpperCase() + (user?.role || 'admin').slice(1) },
                            ].map(item => (
                                <div key={item.label} className="info-row">
                                    <span style={{ fontSize: '0.875rem', color: 'var(--text-muted)' }}>{item.label}</span>
                                    <span style={{ fontSize: '0.875rem', fontWeight: 500, color: 'var(--text-primary)' }}>{item.value}</span>
                                </div>
                            ))}
                        </div>
                    </div>

                    {/* System Info */}
                    <div className="glass-card" style={{ padding: 24 }}>
                        <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 16 }}>
                            <HiOutlineServerStack style={{ width: 20, height: 20, color: '#8b5cf6' }} />
                            <h2 style={{ fontWeight: 700, fontSize: '1rem', color: 'var(--text-primary)' }}>System Info</h2>
                        </div>
                        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                            {[
                                { label: 'Application', value: 'ELVORA v1.0.0' },
                                { label: 'Frontend', value: 'React 19 + Vite 8' },
                                { label: 'Backend', value: 'Node.js + Express 5' },
                                { label: 'Database', value: 'MongoDB Atlas' },
                                { label: 'Loan Period', value: '14 Days' },
                                { label: 'Fine Rate', value: '₹5 / Day' },
                                { label: 'Max Books/Student', value: '5' },
                            ].map(item => (
                                <div key={item.label} className="info-row">
                                    <span style={{ fontSize: '0.875rem', color: 'var(--text-muted)' }}>{item.label}</span>
                                    <span style={{ fontSize: '0.875rem', fontWeight: 500, color: 'var(--text-primary)' }}>{item.value}</span>
                                </div>
                            ))}
                        </div>
                    </div>
                </div>
            </div>
        </div>
    );
};

export default SettingsPage;
